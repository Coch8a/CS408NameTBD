-- Initial proposal schema. Authentication and roster operations arrive later.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE factions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(500) NOT NULL DEFAULT ''
);
CREATE TABLE units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faction_id BIGINT NOT NULL REFERENCES factions(id),
    name VARCHAR(120) NOT NULL,
    base_cost INTEGER NOT NULL CHECK (base_cost >= 0),
    unit_type VARCHAR(50) NOT NULL,
    unit_limit INTEGER CHECK (unit_limit > 0),
    UNIQUE (faction_id, name)
);
CREATE TABLE equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    cost INTEGER NOT NULL CHECK (cost >= 0),
    equipment_type VARCHAR(50) NOT NULL
);
CREATE TABLE rosters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    faction_id BIGINT NOT NULL REFERENCES factions(id),
    roster_name VARCHAR(120) NOT NULL,
    ducat_limit INTEGER NOT NULL CHECK (ducat_limit > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE roster_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roster_id BIGINT NOT NULL REFERENCES rosters(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES units(id),
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0)
);
CREATE TABLE roster_equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roster_unit_id BIGINT NOT NULL REFERENCES roster_units(id) ON DELETE CASCADE,
    equipment_id BIGINT NOT NULL REFERENCES equipment(id),
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    UNIQUE (roster_unit_id, equipment_id)
);
CREATE INDEX idx_units_faction ON units(faction_id);
CREATE INDEX idx_rosters_user ON rosters(user_id);
CREATE INDEX idx_roster_units_roster ON roster_units(roster_id);
