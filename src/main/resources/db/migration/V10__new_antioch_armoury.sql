INSERT INTO unit_equipment_rules (unit_id,equipment_id)
SELECT u.id,e.id FROM units u JOIN equipment e ON e.faction_id=u.faction_id
JOIN factions f ON f.id=u.faction_id WHERE f.slug='new-antioch'
AND NOT EXISTS (SELECT 1 FROM unit_equipment_rules r WHERE r.unit_id=u.id AND r.equipment_id=e.id)
AND e.name NOT IN ('Machine Armour','Reinforced Armour','Standard Armour','Engineer Body Armour','Misericordia')
AND (NOT EXISTS (SELECT 1 FROM equipment_profile_rules r WHERE r.equipment_id=e.id AND r.rule_code='elite-only')
     OR EXISTS (SELECT 1 FROM unit_profile_rules r WHERE r.unit_id=u.id AND r.rule_code='elite'))
AND (NOT e.requires_machine_armour OR EXISTS (
    SELECT 1 FROM unit_equipment_rules r JOIN equipment armour ON armour.id=r.equipment_id
    WHERE r.unit_id=u.id AND armour.faction_id=f.id AND armour.name='Machine Armour'));
